<?php
// Prints a copy of classes/dbconnection.class.php whose connect() can reach
// only the two disposable databases of one test run. Used by run.sh on the
// temporary copy of the code; never written into the live tree.
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }

$source = file_get_contents($argv[1] ?? '');
if ($source === false || strpos($source, 'class dbconnection') === false) {
    fwrite(STDERR, "dbconnection source not found\n");
    exit(2);
}

$count = 0;
$source = preg_replace(
    '/new (?:mysqli|ModuleFlowConnection)\(\s*"[^"]*"\s*,\s*"[^"]*"\s*,\s*"[^"]*"\s*,\s*\$db_name\s*\)/',
    'bflow_test_mysqli($db_name)',
    $source,
    -1,
    $count
);
if ($count !== 1) {
    fwrite(STDERR, "expected exactly one connect() constructor, found {$count}\n");
    exit(2);
}

$guard = <<<'PHP'
<?php
// TEST COPY generated by tests/batch-attendance/make-test-dbconnection.php.
function bflow_test_mysqli($db_name) {
	$tenant = getenv('BFLOW_TENANT_DB');
	$central = getenv('BFLOW_CENTRAL_DB');
	if (!preg_match('/^ccc_database_test_bflow_[a-f0-9]{8}$/D', (string)$tenant) || !preg_match('/^ccc_central_test_bflow_[a-f0-9]{8}$/D', (string)$central)) {
		throw new RuntimeException('bflow test connection used outside a test run');
	}
	// Every tenant name (session db_name, hard-coded 'ccc_database', ...) maps to the disposable tenant.
	$target = ($db_name === 'ccc_central' || $db_name === $central) ? $central : $tenant;
	return new ModuleFlowConnection('localhost', getenv('BFLOW_DB_USER'), getenv('BFLOW_DB_PASS'), $target);
}
PHP;

echo $guard . "\n?>" . $source;
